#!/usr/bin/env python3
"""
Run repro.py through several type checkers and write REPORT.md.

Usage: python3 report.py [--out REPORT.md]

Needs only `uv` on PATH; each checker is fetched and run with `uvx` at the
exact version listed in CHECKERS, so the report can be regenerated anywhere.
"""

import argparse
import dataclasses
import platform
import re
import subprocess
import sys
from collections.abc import Callable
from pathlib import Path

HERE = Path(__file__).parent
REPRO = HERE / "repro.py"
PYTHON_VERSION = "3.12"


@dataclasses.dataclass(frozen=True)
class Checker:
    name: str
    version: str
    command: list[str]
    # Maps each line number to the type the checker revealed there.
    parse: Callable[[str], dict[int, str]]


def regex_parser(pattern: str) -> Callable[[str], dict[int, str]]:
    compiled = re.compile(pattern, re.MULTILINE)

    def parse(output: str) -> dict[int, str]:
        return {int(m["line"]): m["type"] for m in compiled.finditer(output)}

    return parse


parse_mypy = regex_parser(r'^repro\.py:(?P<line>\d+): note: Revealed type is "(?:repro\.)?(?P<type>.*)"')
parse_pyright = regex_parser(r'repro\.py:(?P<line>\d+):\d+ - information: Type of "user" is "(?P<type>.*)"')
parse_ty = regex_parser(r"^repro\.py:(?P<line>\d+):\d+: info\[revealed-type\] Revealed type: `(?P<type>.*)`")
parse_pyrefly = regex_parser(r"^\s*INFO repro\.py:(?P<line>\d+):\d+-\d+: revealed type: (?P<type>.*) \[reveal-type\]")


def mypy(version: str) -> Checker:
    return Checker(
        "mypy",
        version,
        ["uvx", "--python", PYTHON_VERSION, f"mypy@{version}", "--no-incremental", "repro.py"],
        parse_mypy,
    )


CHECKERS = [
    mypy("1.19.1"),
    mypy("1.20.0"),
    mypy("1.20.2"),
    mypy("2.0.0"),
    mypy("2.1.0"),
    mypy("2.2.0"),
    mypy("2.3.1"),
    mypy("2.4.0"),
    Checker("pyright", "1.1.414", ["uvx", "pyright@1.1.414", "repro.py"], parse_pyright),
    Checker(
        "pyrefly",
        "1.3.2",
        ["uvx", "pyrefly@1.3.2", "check", "repro.py", "--preset", "default", "--output-format", "min-text"],
        parse_pyrefly,
    ),
    Checker(
        "ty",
        "0.0.86",
        ["uvx", "ty@0.0.86", "check", "--python-version", PYTHON_VERSION, "--output-format", "concise", "repro.py"],
        parse_ty,
    ),
]


def marker_line(marker: str) -> int:
    for number, line in enumerate(REPRO.read_text().splitlines(), start=1):
        if marker in line:
            return number
    raise SystemExit(f"marker {marker!r} not found in {REPRO}")


def run(checker: Checker) -> tuple[str, str]:
    proc = subprocess.run(checker.command, cwd=HERE, capture_output=True, text=True)
    return proc.stdout + proc.stderr, " ".join(checker.command)


def render(out: Path) -> None:
    if_line = marker_line("# if-branch")
    else_line = marker_line("# else-branch")
    rows: list[str] = []
    details: list[str] = []
    for checker in CHECKERS:
        print(f"running {checker.name} {checker.version}", file=sys.stderr)
        output, command = run(checker)
        revealed = checker.parse(output)
        if_type = revealed.get(if_line, "(no output)")
        # ty prints intersections such as `User & ~Admin` for a narrowed else-branch.
        else_type = revealed.get(else_line, "unreachable")
        correct = if_type == "Admin"
        verdict = "narrows" if correct else "**does not narrow**"
        rows.append(f"| {checker.name} | {checker.version} | `{if_type}` | `{else_type}` | {verdict} |")
        details.append(f"<details><summary>{checker.name} {checker.version}</summary>\n\n```\n$ {command}\n{output.strip()}\n```\n\n</details>")

    uv_version = subprocess.run(["uv", "--version"], capture_output=True, text=True).stdout.strip()
    source = REPRO.read_text().rstrip()
    out.write_text(
        "\n".join(
            [
                "# `TypeIs[NewType]` narrowing across type checkers",
                "",
                "`reveal_type(user)` in each branch of `if is_admin(user):` for the program below.",
                f"A checker that narrows reports `Admin` in the if-branch. Generated by `report.py` with {uv_version} "
                f"on {platform.system()} {platform.machine()}, checking as Python {PYTHON_VERSION}.",
                "",
                "```python",
                source,
                "```",
                "",
                "| Checker | Version | if-branch | else-branch | Result |",
                "|---|---|---|---|---|",
                *rows,
                "",
                "## Raw output",
                "",
                *details,
                "",
            ]
        )
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=HERE / "REPORT.md")
    args = parser.parse_args()
    render(args.out)
    print(f"wrote {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
